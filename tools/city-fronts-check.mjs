// ═══════════════════════════════════════════════════════════════════════════
// city-fronts.mjs — publishes the colony tables the battlefield derives from.
//
//   node tools/city-fronts-check.mjs           assert the shipped copy is current
//   node tools/city-fronts-check.mjs --write   regenerate it
//
// Named *-check.mjs so tools/run-all.mjs discovers it, and it therefore
// DEFAULTS to asserting: a check that has to be asked to check will not be run.
//
// *** WHY THIS EXISTS: A BUG, AND ONE THE HEADLESS HARNESS COULD NOT SEE. ***
// CB.mapFor derives every battlefield from COLONY_META and COLONY_VISUAL.
// COLONY_META is on the client - galaxy.js publishes it as _FM_COLONY_META.
// COLONY_VISUAL IS NOT. It is exported from server/city.js and has never been
// sent to a browser, so in the live client every colony fell through to the
// grid/dust default: sixty-six fronts collapsing to one, silently, on a code
// path that renders perfectly and simply describes the wrong world.
//
// It survived review because tools/citybattle-harness.mjs INJECTS both tables
// itself, parsed straight out of the source files. That is the right thing for
// a harness to do and it meant the harness was the only consumer that could
// never hit the bug. A test that supplies the input the product is missing
// will pass forever.
//
// The fix is the pattern this repo already uses for planet-palette.js: a
// GENERATED file, never hand edited, with a --check that asserts it still
// matches its source. Not a second authority - a published copy of the first,
// and one that cannot drift without a check going red.
//
// WHAT IS PUBLISHED, and it is deliberately not everything: the battlefield
// needs a colony's visual row, its name, which space it is in, its population
// and the name and sector of each zone. It does not need lore, companies,
// coordinates or bonuses, and shipping those would make this a second copy of
// COLONY_META rather than an extract from it.
// ═══════════════════════════════════════════════════════════════════════════
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'client', 'assets', 'space', 'city-fronts.js');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

function braceBlock(src, marker) {
  const i = src.indexOf(marker);
  if (i < 0) throw new Error('not found: ' + marker);
  let d = 0, j = src.indexOf('{', i), st = j;
  for (; j < src.length; j++) {
    if (src[j] === '{') d++;
    else if (src[j] === '}') { d--; if (!d) { j++; break; } }
  }
  return (0, eval)('(' + src.slice(st, j) + ')');
}

const META = braceBlock(read('client/assets/galaxy.js'), 'var COLONY_META = {');
const VISUAL = braceBlock(read('server/city.js'), 'export const COLONY_VISUAL = {');

const meta = {};
for (const id of Object.keys(META)) {
  if (/^ks_/.test(id)) continue;                 // the brood has reach-battle
  const c = META[id];
  meta[id] = {
    name: c.name,
    galaxy: c.galaxy || null,
    pop: c.pop || null,
    planets: (c.planets || []).map((p) => ({ name: p.name, sectorName: p.sectorName })),
  };
}
const visual = {};
for (const id of Object.keys(VISUAL)) {
  if (/^ks_/.test(id)) continue;
  visual[id] = { layout: VISUAL[id].layout, terrain: VISUAL[id].terrain };
}

const body = `// GENERATED by tools/city-fronts.mjs - DO NOT EDIT BY HAND.
// Regenerate after changing COLONY_META in client/assets/galaxy.js or
// COLONY_VISUAL in server/city.js:   node tools/city-fronts.mjs
//
// COLONY_VISUAL lives on the SERVER and is never sent to a browser. The city
// battlefield derives every front from it, so without this file the client
// falls back to grid/dust for all sixty-six of them - rendering perfectly and
// describing the wrong world. This is a published copy of the server's table,
// not a second authority: tools/city-fronts.mjs --check asserts it matches.
(function () {
'use strict';
window.FM_CITY_FRONTS = {
  meta: ${JSON.stringify(meta, null, 1)},
  visual: ${JSON.stringify(visual, null, 1)}
};
})();
`;

const check = !process.argv.includes('--write');
const zones = Object.values(meta).reduce((a, c) => a + c.planets.length, 0);
console.log('colonies:', Object.keys(meta).length, ' zones:', zones,
            ' visual rows:', Object.keys(visual).length);

if (check) {
  if (!fs.existsSync(OUT)) {
    console.error('FAIL: ' + path.relative(ROOT, OUT) + ' is not shipped');
    process.exit(1);
  }
  if (fs.readFileSync(OUT, 'utf8') !== body) {
    console.error('FAIL: the shipped table is stale.  node tools/city-fronts.mjs');
    process.exit(1);
  }
  console.log('city-fronts: green');
} else {
  fs.writeFileSync(OUT, body);
  console.log('wrote', path.relative(ROOT, OUT));
}
