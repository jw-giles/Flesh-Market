// ═══════════════════════════════════════════════════════════════════════════
// bench-manifests.mjs  ->  client/assets/space/bench-manifests.js
//
// THE BENCH LOST ITS TERRAIN AND ITS ENEMIES TO A BLOCKED fetch, and neither
// failure said anything.
//
// loadMeshes() fetches assets/space/nature/meshes.json and, on failure, sets
// _meshPend = 2 with the comment "wireframe keeps the field". loadBrood()
// fetches assets/space/brood/geometry.json and, on failure, sets _broodReq = 2.
// Both are correct for the game: a manifest that will not load must not take
// the battlefield down with it.
//
// fetch IS BLOCKED ON file:// IN CHROME. So a bench opened off the disk gets:
//
//   no nature meshes  -> every rock, ridge and block draws as an untextured
//                        prism. That is the flat tan slab terrain.
//   no brood geometry -> every creature falls to wireframe. Those are the
//                        wireframe enemies.
//
// Both modules already have an override for exactly this: FM_NATURE_SRC and
// FM_BROOD_GEOM take an OBJECT and skip the fetch entirely. This generates a
// script that sets them, so the bench never touches fetch.
//
// GENERATED, NOT HAND-COPIED, and asserted current by tools/reach-check.mjs.
// The alternative was pasting two JSON files into an HTML page, which is a
// second copy of a thing that changes: brood geometry has been regenerated
// twice already, and a bench holding a stale frame index would strobe or walk
// into the next creature's attack row rather than fail visibly.
//
//   node tools/bench-manifests.mjs
// ═══════════════════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GALAXY = 'client/assets/galaxy.js';
const NATURE = 'client/assets/space/nature/meshes.json';
const BROOD  = 'client/assets/space/brood/geometry.json';
const OUT    = 'client/assets/space/bench-manifests.js';

function readJson(rel) {
  const p = path.join(ROOT, rel);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const nature = readJson(NATURE);
const brood = readJson(BROOD);

/* ── The other half of the terrain fault, and it is not about file:// ──────
   THE BENCH NEVER LOADED THE PLANET TABLES, so it has been drawing the LEGACY
   FALLBACK PALETTE since the day it shipped - wrong over http as well as off
   the disk.

   paletteFor() reads window.PLANET_PALETTE and window.COLONY_PLANET; terrainKey()
   reads window.REACH_TERRAIN. All three come out of galaxy.js and
   planet-palette.js, and the bench loaded neither, so every lookup missed and
   the battlefield fell through to TERRAIN_COL - the hand-written table whose own
   comment records that four of ten Reach worlds fought on a colour their planet
   is not. That fallback is correct as a fallback and is exactly the wrong thing
   for a bench, whose entire claim is that what you see is what the game does.

   galaxy.js is seven thousand lines and binds a map view; loading it here to
   get two tables would drag the galaxy renderer into a page with none of its
   DOM. So the tables are LIFTED, by brace matching, and emitted. Hand-copying
   them was the other option and is the drift this whole file exists to avoid:
   that table has already been out of step with the art once. */
function liftObject(src, decl) {
  const i = src.indexOf(decl);
  if (i < 0) return null;
  let d = 0, start = src.indexOf('{', i);
  if (start < 0) return null;
  for (let k = start; k < src.length; k++) {
    if (src[k] === '{') d++;
    else if (src[k] === '}' && --d === 0) return src.slice(start, k + 1);
  }
  return null;
}
const galaxySrc = fs.existsSync(path.join(ROOT, GALAXY))
  ? fs.readFileSync(path.join(ROOT, GALAXY), 'utf8') : '';
const colonyPlanet = liftObject(galaxySrc, 'var COLONY_PLANET = ');
const reachTerrain = liftObject(galaxySrc, 'window.REACH_TERRAIN = ');

/* A MISSING SOURCE IS NOT A REASON TO WRITE AN EMPTY MANIFEST. The brood sheets
   are gitignored for licence reasons, so geometry.json can legitimately be
   absent on a fresh clone, and emitting `FM_BROOD_GEOM = {}` there would set the
   override to a value that means "registered, and empty" rather than leaving it
   unset - which is worse than the fetch it replaces, because the fetch at least
   falls back to wireframe honestly. Omit the global instead. */
const parts = [];
parts.push(`// GENERATED by tools/bench-manifests.mjs. Do not edit.
//
// Sets the two manifest overrides the bench needs because fetch is blocked on
// file:// URLs. Loaded ONLY by client/battle-test.html; the game fetches these
// at runtime and never sees this file.
//
// Both globals are read once, before the module that consumes them decides
// whether to fetch, so this has to be loaded BEFORE coalition-sprites.js and
// reach-battle.js.`);

/* Emitted as the SOURCE TEXT rather than re-serialised, so a diff against
   galaxy.js is a diff and not a reformatting. */
if (colonyPlanet) parts.push('window.COLONY_PLANET = ' + colonyPlanet + ';');
else parts.push('// COLONY_PLANET could not be lifted from galaxy.js.');
if (reachTerrain) parts.push('window.REACH_TERRAIN = ' + reachTerrain + ';');
else parts.push('// REACH_TERRAIN could not be lifted from galaxy.js.');

if (nature) parts.push(`window.FM_NATURE_SRC = ${JSON.stringify(nature)};`);
else parts.push(`// nature/meshes.json absent at generation time: no override emitted,\n// so loadMeshes() takes its normal fetch path and its normal fallback.`);

if (brood) parts.push(`window.FM_BROOD_GEOM = ${JSON.stringify(brood)};`);
else parts.push(`// brood/geometry.json absent at generation time (the pack is gitignored):\n// no override emitted, so loadBrood() takes its normal fetch path.`);

const out = parts.join('\n\n') + '\n';
fs.writeFileSync(path.join(ROOT, OUT), out);

console.log('wrote ' + OUT
  + ' (' + (nature ? Object.keys(nature).length + ' mesh entries' : 'no meshes')
  + ', ' + (brood ? Object.keys(brood).length + ' brood sheets' : 'no brood')
  + ', ' + (colonyPlanet ? 'planets' : 'NO PLANETS')
  + ', ' + (reachTerrain ? 'terrain keys' : 'NO TERRAIN KEYS')
  + ', ' + Math.round(out.length / 1024) + 'kb)');
